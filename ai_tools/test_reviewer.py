import ollama

API_REVIEW_RULES = """
Правила код-ревью API-автотестов в этом проекте:
1. Тест не должен хардкодить токены/креды в коде — авторизация должна идти через фикстуру.
2. Assert должен проверять не только status code, но и структуру/содержимое ответа (например, через Pydantic-модель или явную проверку полей), а не просто "запрос прошёл".
3. Для эндпоинтов с side-effects (создание/изменение данных) тест должен проверять идемпотентность — либо явно тестировать повторный вызов, либо гарантировать очистку созданных данных после теста (teardown).
4. Не должно быть "магических" ожиданий вроде time.sleep(N) для асинхронных операций — используй polling с таймаутом.
5. URL эндпоинта не должен быть хардкожен в теле теста — берётся из конфига/фикстуры base_url.
"""

def review_test_code(test_code: str, rules: str = API_REVIEW_RULES) -> str:
    prompt = f"""Ты проводишь код-ревью автотеста. Проверь код на соответствие правилам ниже и укажи конкретные нарушения со ссылкой на строку/фрагмент кода. Если нарушений нет — так и скажи.

{rules}

Код теста для ревью:
{test_code}
"""
    response = ollama.chat(
        model="llama3.1:8b",
        messages=[{"role": "user", "content": prompt}]
    )
    return response["message"]["content"].strip()